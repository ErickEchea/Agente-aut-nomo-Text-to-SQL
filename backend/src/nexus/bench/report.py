"""Render docs/benchmark.md from bench/results (the latest full run of each configuration)."""

from __future__ import annotations

from collections.abc import Sequence

from nexus.bench.golden import GoldenSet
from nexus.bench.metrics import REFERENCE_ITEMS, SELECTION_MARGIN, is_eligible, select_default
from nexus.bench.store import RunRecord

REASON_TEXT = {
    "row_values": "wrong values",
    "row_count": "wrong number of rows",
    "missing_column": "an expected column is missing",
    "order": "right rows, wrong order",
    "no_result": "no result",
    "answered_ambiguous": "answered instead of asking",
    "status_clarification": "asked for clarification instead of answering",
    "status_failed": "failed after repairs",
    "status_refused": "refused",
    "llm_error": "model error or timeout",
}


def _pct(value: float | None) -> str:
    return "–" if value is None else f"{value * 100:.1f} %"


def _secs(ms: float) -> str:
    return f"{ms / 1000:.1f} s"


def latest_by_config(records: Sequence[RunRecord], subset: str = "full") -> dict[str, RunRecord]:
    latest: dict[str, RunRecord] = {}
    for record in sorted(records, key=lambda r: r.finished_at):
        if record.subset == subset:
            latest[record.config.name] = record
    return latest


def eligible_configs(latest: dict[str, RunRecord]) -> set[str]:
    return {
        name
        for name, record in latest.items()
        if is_eligible({o.item_id for o in record.outcomes if o.correct})
    }


def render(records: Sequence[RunRecord], golden: GoldenSet, *, hardware: str) -> str:
    latest = latest_by_config(records)
    summaries = {name: record.summary for name, record in latest.items()}
    eligible = eligible_configs(latest)
    chosen = select_default(summaries, eligible)
    counts = golden.counts()
    lines = [
        "# Benchmark",
        "",
        "Golden-set execution accuracy of NEXUS AI per model configuration. Methodology:",
        "[ADR-0015](adr/0015-benchmark-methodology.md); decision: "
        "[ADR-0022](adr/0022-default-model-from-benchmark.md). Generated by `make bench-report`",
        "from `bench/results/`; do not edit by hand.",
        "",
        f"- **Golden set**: {len(golden.items)} questions — "
        + ", ".join(f"{n} {d}" for d, n in counts.items())
        + ".",
        f"- **Hardware**: {hardware}.",
    ]
    if latest:
        any_record = next(iter(latest.values()))
        lines += [
            f"- **Dataset**: retail demo v{any_record.dataset_version}, reference date 2026-11-01.",
            "- **Decoding**: temperature 0, fixed seeds; one warm-up question per configuration is "
            "excluded from latency.",
        ]
    lines += ["", "## Results", ""]
    if not latest:
        lines += ["No completed full runs yet: run `make bench`.", ""]
        return "\n".join(lines)

    lines += [
        "| Configuration | Models | Accuracy | Easy | Medium | Hard | Ambiguous | p50 | p95 | "
        "1st-try SQL ok | Recovery | Tokens/q | Summary fallback | Recall@5 | Reference question |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, record in sorted(latest.items(), key=lambda kv: -kv[1].summary.accuracy):
        s = record.summary
        by = s.by_difficulty
        cells = [
            f"**{name}**" if name == chosen else name,
            ", ".join(f"`{m}`" for m in record.config.models)
            + (" (think off)" if record.config.think is False else ""),
            f"**{_pct(s.accuracy)}** ({s.correct}/{s.items})",
            *(
                _pct(by[d].accuracy) if d in by else "–"
                for d in ("easy", "medium", "hard", "ambiguous")
            ),
            _secs(s.latency_p50_ms),
            _secs(s.latency_p95_ms),
            _pct(s.first_attempt_rate),
            _pct(s.recovery_rate),
            f"{s.tokens_per_question:,.0f}",
            _pct(s.grounding_fallback_rate),
            _pct(s.recall_at_5),
            "✓" if name in eligible else "✗ (not eligible)",
        ]
        lines.append("| " + " | ".join(cells) + " |")

    lines += [
        "",
        "## Default model",
        "",
        f"Rule (ADR-0003 §4, ADR-0022): only configurations that answer the reference question "
        f"({', '.join(REFERENCE_ITEMS)}) are eligible; among them, the highest accuracy wins, and "
        f"within {SELECTION_MARGIN * 100:.0f} points of it the lowest p95 latency.",
        "",
        f"**Selected: `{chosen}`.**" if chosen else "No configuration selected.",
        "",
        "## Latency per agent node (mean per question)",
        "",
    ]
    nodes = sorted({n for r in latest.values() for n in r.summary.node_latency_ms})
    lines += [
        "| Configuration | " + " | ".join(nodes) + " |",
        "|---|" + "---|" * len(nodes),
    ]
    for name, record in sorted(latest.items()):
        per_node = record.summary.node_latency_ms
        lines.append(
            f"| {name} | "
            + " | ".join(_secs(per_node[n]) if n in per_node else "–" for n in nodes)
            + " |"
        )

    lines += ["", "## Why answers were wrong", ""]
    for name, record in sorted(latest.items()):
        reasons = ", ".join(
            f"{REASON_TEXT.get(reason, reason)}: {count}"
            for reason, count in record.summary.reasons.items()
        )
        lines.append(f"- **{name}** — {reasons or 'none'}")

    if chosen:
        record = latest[chosen]
        misses = [o for o in record.outcomes if not o.correct]
        lines += [
            "",
            f"## Questions the selected configuration got wrong ({len(misses)})",
            "",
            "| Id | Question | Outcome |",
            "|---|---|---|",
        ]
        for outcome in misses:
            question = outcome.question.replace("|", "\\|")
            lines.append(
                f"| {outcome.item_id} | {question} | {REASON_TEXT.get(outcome.reason, outcome.reason)} |"
            )
    lines.append("")
    return "\n".join(lines)
